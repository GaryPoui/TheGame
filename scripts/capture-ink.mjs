import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const baseURL = process.env.PLAYWRIGHT_BASE_URL ?? 'http://127.0.0.1:4174/';
const out = 'docs/evidence/ink';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [], failed = [], badResponses = [], external = [];
page.on('pageerror', e => errors.push(e.message));
page.on('requestfailed', r => failed.push(r.url()));
page.on('response', r => { if (r.status() >= 400) badResponses.push({ url: r.url(), status: r.status() }); });
page.on('request', r => { if (new URL(r.url()).origin !== new URL(baseURL).origin) external.push(r.url()); });
try {
  await page.goto(baseURL);
  await page.waitForLoadState('networkidle');
  await page.waitForFunction(() => window.__THEGAME_READY__);
  await page.screenshot({ path: `${out}/final-menu.png` });
  await page.getByTestId('new-game').click();
  await page.waitForFunction(() => document.body.dataset.introPhase === 'lit');
  await page.waitForTimeout(1300);
  await page.screenshot({ path: `${out}/final-intro.png` });
  await page.getByTestId('skip-intro').click();
  await page.getByTestId('enter-urns').click();
  await page.getByTestId('skip-tutorial').click();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${out}/final-table.png` });
  const metrics = await page.evaluate(() => window.__THEGAME_METRICS__?.());
  const resources = await page.evaluate(() => performance.getEntriesByType('resource').map(r => ({ url: r.name, bytes: r.encodedBodySize })));
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.getByTestId('settings-button').click();
  await page.getByTestId('reduced-motion').check();
  await page.getByTestId('text-scale').selectOption('2');
  await page.getByTestId('close-dialog').click();
  await page.screenshot({ path: `${out}/final-text-200.png`, fullPage: true });
  await page.getByTestId('urn-0').click();
  await page.getByTestId('confirm-choice').click();
  await page.getByTestId('settings-button').click();
  await page.getByTestId('text-scale').selectOption('1');
  await page.getByTestId('close-dialog').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${out}/final-narrow.png`, fullPage: true });
  const narrow = await page.evaluate(() => ({ viewport: innerWidth, width: document.documentElement.scrollWidth }));
  const report = { baseURL, date: new Date().toISOString(), browser: browser.version(), metrics, narrow, errors, failed, badResponses, external, resources, note: 'Software SwiftShader; no hardware GPU benchmark.' };
  await writeFile(`${out}/capture.json`, JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify({ baseURL, errors, failed, badResponses, external, narrow, metrics }));
  if (errors.length || failed.length || badResponses.length || external.length || narrow.width > narrow.viewport) process.exitCode = 1;
} finally { await browser.close(); }
